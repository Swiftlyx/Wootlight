/// The name of an effect, or "Off".
pub fn effect_label(effect: Option<Effect>) -> T {
    match effect {
        None => T::EffectOff,
        Some(Effect::Rain) => T::EffectRain,
        Some(Effect::Storm) => T::EffectStorm,
        Some(Effect::Matrix) => T::EffectMatrix,
        Some(Effect::Snow) => T::EffectSnow,
        Some(Effect::Stars) => T::EffectStars,
        Some(Effect::Aurora) => T::EffectAurora,
        Some(Effect::Ripples) => T::EffectRipples,
        Some(Effect::Fire) => T::EffectFire,
        Some(Effect::Life) => T::EffectLife,
        Some(Effect::Clock) => T::EffectClock,
        Some(Effect::Snake) => T::EffectSnake,
    }
}

